def build():
    src = open(os.path.join(ROOT, 'index.html'), encoding='utf8').read()
    out = src
    problems = []
    for entry in PAIRS:
        en, zh = entry[0], entry[1]
        want = entry[2] if len(entry) > 2 else 1
        n = out.count(en)
        if n != want:
            problems.append(f'expected {want}x, found {n}x: {en[:90]!r}')
            continue
        out = out.replace(en, zh)
    if problems:
        print('Translation table is out of date with index.html:')
        for p in problems:
            print('  -', p)
        sys.exit(1)
    # the Chinese page lives one folder down: fix relative asset paths
    out = re.sub(r'(?<=["(,\s])assets/', '../assets/', out)
    out = out.replace('href="favicon.svg"', 'href="../favicon.svg"')
    os.makedirs(os.path.join(ROOT, 'zh'), exist_ok=True)
    with open(os.path.join(ROOT, 'zh', 'index.html'), 'w', encoding='utf8', newline='\n') as f:
        f.write(out)
    print(f'zh/index.html written ({len(PAIRS)} translations applied)')


if __name__ == '__main__':
    build()
